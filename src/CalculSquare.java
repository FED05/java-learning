public class CalculSquare {
    public static void CalculSquareNumber(int n){
        int result = n*n;
        System.out.println("square of number  "+ n + " is " + result);
    }
    public static void main(String[] args){
        CalculSquareNumber(4);
        CalculSquareNumber(6);
        CalculSquareNumber(8);
    }
}
